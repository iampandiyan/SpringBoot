#!/usr/bin/env python3
"""
Docs-as-tested check for one lesson.

What it does
  1. Starts a work folder: a copy of the previous lesson's reference (or empty for lesson 00,
     plus the Maven wrapper files, which the lesson tells the learner to generate by command).
  2. Extracts every code block that is announced in the lesson with a line of the form
        **File:** `relative/path/File.java`
     followed by a fenced code block, and writes the blocks in document order
     (a later block for the same path replaces the earlier one, as a learner's edit would).
  3. Compares the work folder with the lesson's reference folder (must be identical).
  4. Runs `mvnw clean verify` in the work folder (skip with --no-build).
  5. Checks the 11 required section headings exist in the lesson README.

Usage
  python tools/check_lesson.py <lesson README> <reference dir> [--prev <previous reference dir>]
         [--wrapper <dir containing mvnw, mvnw.cmd, .mvn>] [--work <dir>] [--no-build]
Exit code 0 = all good.
"""
import argparse, os, re, shutil, subprocess, sys

HEADINGS = [
    "## 1. Goal and time box", "## 2. Why it matters", "## 3. Concepts explained like a teacher",
    "## 4. Setup steps", "## 5. Code walkthrough", "## 6. Common mistakes",
    "## 7. Production issues and design notes", "## 8. Architect lens", "## 9. Self-check quiz",
    "## 10. Interview Q&A", "## 11. Recap",
]
SKIP_DIRS = {"target", ".git"}
WRAPPER = {"mvnw", "mvnw.cmd", ".mvn"}


def extract_blocks(md_text):
    """Yield (path, content) for each **File:** `path` + fenced block."""
    lines = md_text.splitlines()
    i = 0
    while i < len(lines):
        m = re.match(r"^\*\*File:\*\*\s+`([^`]+)`\s*$", lines[i])
        if m:
            path = m.group(1)
            j = i + 1
            while j < len(lines) and lines[j].strip() == "":
                j += 1
            if j < len(lines) and lines[j].startswith("```"):
                fence = lines[j][:3]
                k = j + 1
                body = []
                while k < len(lines) and not lines[k].startswith(fence):
                    body.append(lines[k])
                    k += 1
                yield path, "\n".join(body) + "\n"
                i = k
        i += 1


def copy_tree(src, dst):
    for root, dirs, files in os.walk(src):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        rel = os.path.relpath(root, src)
        os.makedirs(os.path.join(dst, rel), exist_ok=True)
        for f in files:
            shutil.copy2(os.path.join(root, f), os.path.join(dst, rel, f))


def norm(s):
    return "\n".join(l.rstrip() for l in s.replace("\r\n", "\n").split("\n")).strip() + "\n"


def list_files(base):
    out = {}
    for root, dirs, files in os.walk(base):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for f in files:
            full = os.path.join(root, f)
            rel = os.path.relpath(full, base).replace("\\", "/")
            top = rel.split("/")[0]
            if top in WRAPPER:   # wrapper files are generated by a command, not typed
                continue
            out[rel] = full
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("readme")
    ap.add_argument("reference")
    ap.add_argument("--prev")
    ap.add_argument("--wrapper")
    ap.add_argument("--work", default=os.path.join(os.environ.get("TEMP", "."), "lesson-check"))
    ap.add_argument("--no-build", action="store_true")
    a = ap.parse_args()

    problems = []
    text = open(a.readme, encoding="utf-8").read()

    # 5. headings
    for h in HEADINGS:
        if not re.search(r"^" + re.escape(h) + r"\s*$", text, re.M):
            problems.append(f"missing heading: {h}")

    # 1. work folder
    if os.path.exists(a.work):
        shutil.rmtree(a.work)
    os.makedirs(a.work)
    if a.prev:
        copy_tree(a.prev, a.work)
    wrapper_src = a.wrapper or a.prev or a.reference
    for w in WRAPPER:
        s = os.path.join(wrapper_src, w)
        d = os.path.join(a.work, w)
        if os.path.isdir(s):
            shutil.copytree(s, d, dirs_exist_ok=True)
        elif os.path.isfile(s):
            shutil.copy2(s, d)

    # 2. extract
    n = 0
    for path, content in extract_blocks(text):
        full = os.path.join(a.work, *path.split("/"))
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        n += 1
    print(f"extracted {n} file block(s)")

    # 3. compare
    ref, work = list_files(a.reference), list_files(a.work)
    for rel in sorted(ref):
        if rel not in work:
            problems.append(f"in reference but not produced by the lesson: {rel}")
        elif norm(open(ref[rel], encoding="utf-8").read()) != norm(open(work[rel], encoding="utf-8").read()):
            problems.append(f"content differs from reference: {rel}")
    for rel in sorted(work):
        if rel not in ref:
            problems.append(f"produced by the lesson but not in reference: {rel}")

    # 4. build
    if not a.no_build and not problems:
        wrapper_cmd = os.path.join(os.path.abspath(a.work), "mvnw.cmd" if os.name == "nt" else "mvnw")
        cmd = ["cmd", "/c", wrapper_cmd, "-q", "clean", "verify"] if os.name == "nt" else [wrapper_cmd, "-q", "clean", "verify"]
        r = subprocess.run(cmd, cwd=a.work, capture_output=True, text=True)
        if r.returncode != 0:
            problems.append("build failed:\n" + (r.stdout + r.stderr)[-2000:])
        else:
            print("build + tests: OK")

    if problems:
        print("PROBLEMS:")
        for p in problems:
            print("  -", p)
        sys.exit(1)
    print("lesson check: PASS")


if __name__ == "__main__":
    main()
